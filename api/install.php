<?php
// One-time setup page. Open this in a browser after uploading.
// It writes config.php, creates the database tables, and makes the first
// (admin) account. Delete this file afterwards.

declare(strict_types=1);

$configPath = __DIR__ . '/config.php';
$alreadyInstalled = is_file($configPath);
$done = false;
$error = '';
$notice = '';

function h(string $s): string { return htmlspecialchars($s, ENT_QUOTES, 'UTF-8'); }

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
    $dbHost = trim($_POST['db_host'] ?? 'localhost');
    $dbPort = (int) ($_POST['db_port'] ?? 3306);
    $dbName = trim($_POST['db_name'] ?? '');
    $dbUser = trim($_POST['db_user'] ?? '');
    $dbPass = (string) ($_POST['db_pass'] ?? '');
    $signup = trim($_POST['signup_code'] ?? '');
    $adminUser = strtolower(trim($_POST['admin_user'] ?? ''));
    $adminPass = (string) ($_POST['admin_pass'] ?? '');
    $adminName = trim($_POST['admin_name'] ?? '');

    if ($dbName === '' || $dbUser === '') {
        $error = 'Database name and database user are required.';
    } elseif (!preg_match('/^[a-z0-9._]{3,64}$/', $adminUser)) {
        $error = 'Admin username must be 3-64 chars: letters, numbers, dot or underscore.';
    } elseif (strlen($adminPass) < 6) {
        $error = 'Admin password must be at least 6 characters.';
    } else {
        try {
            $dsn = "mysql:host={$dbHost};port={$dbPort};dbname={$dbName};charset=utf8mb4";
            $pdo = new PDO($dsn, $dbUser, $dbPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            ]);
        } catch (PDOException $e) {
            $error = 'Could not connect to the database. Check host, name, user and password. (' . h($e->getMessage()) . ')';
        }

        if ($error === '') {
            // Create schema.
            $pdo->exec('CREATE TABLE IF NOT EXISTS users (
                id VARCHAR(40) PRIMARY KEY, username VARCHAR(64) UNIQUE NOT NULL,
                display_name VARCHAR(128) NOT NULL, phone VARCHAR(32) NULL,
                password_hash VARCHAR(255) NOT NULL, role VARCHAR(16) NOT NULL DEFAULT "member",
                created_at BIGINT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4');
            $pdo->exec('CREATE TABLE IF NOT EXISTS sessions (
                token VARCHAR(64) PRIMARY KEY, user_id VARCHAR(40) NOT NULL,
                created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
                INDEX idx_sess_user (user_id)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4');
            $pdo->exec('CREATE TABLE IF NOT EXISTS records (
                collection VARCHAR(40) NOT NULL, doc_id VARCHAR(160) NOT NULL,
                data MEDIUMTEXT NOT NULL, updated_at BIGINT NOT NULL,
                deleted TINYINT NOT NULL DEFAULT 0, updated_by VARCHAR(40) NULL,
                PRIMARY KEY (collection, doc_id), INDEX idx_rec_updated (updated_at)
                ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4');

            // Write config.php.
            $cfg = "<?php\n// Auto-generated by install.php. Safe to edit by hand.\nreturn " . var_export([
                'db_host' => $dbHost,
                'db_port' => $dbPort,
                'db_name' => $dbName,
                'db_user' => $dbUser,
                'db_pass' => $dbPass,
                'signup_code' => $signup,
            ], true) . ";\n";

            if (@file_put_contents($configPath, $cfg) === false) {
                $error = 'Could not write config.php. Make the /api folder writable (chmod 755) and try again, or create config.php manually.';
            } else {
                // Create the admin account if the username is free.
                $exists = $pdo->prepare('SELECT 1 FROM users WHERE username = ?');
                $exists->execute([$adminUser]);
                if (!$exists->fetch()) {
                    $count = (int) $pdo->query('SELECT COUNT(*) c FROM users')->fetch()['c'];
                    $role = $count === 0 ? 'admin' : 'member';
                    $ins = $pdo->prepare('INSERT INTO users (id, username, display_name, phone, password_hash, role, created_at) VALUES (?,?,?,?,?,?,?)');
                    $ins->execute([
                        bin2hex(random_bytes(16)), $adminUser,
                        $adminName !== '' ? $adminName : $adminUser, null,
                        password_hash($adminPass, PASSWORD_DEFAULT), $role,
                        (int) round(microtime(true) * 1000),
                    ]);
                    $notice = 'Admin account created.';
                } else {
                    $notice = 'That admin username already existed, so it was left unchanged.';
                }
                $done = true;
            }
        }
    }
}
